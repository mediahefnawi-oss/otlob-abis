const THANKS = ['شكرا', 'تسلم', 'متشكر', 'ميرسي', 'جزاك', 'تمام', 'ماشي', 'اوكي', 'اوك', 'ok'];
const HELLO = ['السلام', 'اهلا', 'مرحبا', 'هاي', 'صباح', 'مساء', 'هلا'];

const has = (t, list) => list.some(w => t.includes(norm(w)));

/** → { reply, escalate } */
function answer(text) {
  const t = norm(text);
  if (!t) return { reply: HANDOFF, escalate: true };
  if (has(t, TALK) || has(t, PROBLEM)) return { reply: HANDOFF, escalate: true };
  const hit = TOPICS.find(x => has(t, x.k));
  if (hit) return { reply: hit.a, escalate: false };
  if (t.split(' ').length <= 3 && has(t, THANKS)) return { reply: 'العفو 🌹 لو احتجت أي حاجة تانية أنا هنا.', escalate: false };
  if (t.split(' ').length <= 4 && has(t, HELLO)) return { reply: 'أهلاً بيك 👋 اسألني عن أي حاجة في التطبيق، أو اختار من الأسئلة السريعة تحت. ولو عايز حد من الدعم اضغط «كلم الدعم».', escalate: false };
  return { reply: HANDOFF, escalate: true };
}
