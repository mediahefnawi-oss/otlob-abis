// push to customers when a new offer starts (switch "offerPush", one push per 24h)
const { Pool } = require('./shim');
let pass = 0, bad = 0; const ok = (c, m) => { if (c) pass++; else { bad++; console.log('  FAIL:', m); } };
const eq = (a, b, m) => ok(a === b, `${m}: got ${a}, want ${b}`);
const routes = {}; const app = {};
for (const m of ['get', 'post', 'patch', 'put', 'delete']) app[m] = (p, ...c) => { routes[`${m.toUpperCase()} ${p}`] = c; };
const asyncRoute = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
(async () => {
  const pool = new Pool(); const q = (t, p) => pool.query(t, p);
  const sent = [];
  const pushToUsers = async (ids, p) => { sent.push({ ids, p }); };
  const roles = (...a) => (req, res, next) => (a.includes(req.auth.role) ? next() : next(Object.assign(new Error('no'), { http: 403 })));
  const positiveId = v => { const n = Number(v); return Number.isSafeInteger(n) && n > 0 ? n : null; };
  require('../src/offers.js').registerOfferRoutes(app, { pool, auth: (r, s, n) => n(), roles, asyncRoute, positiveId, pushToUsers });
  const call = (key, as, body) => new Promise(resolve => {
    const chain = routes[key];
    const res = { set() { return this; }, status(c) { this.c = c; return this; }, json(j) { resolve({ status: this.c || 200, json: j }); return this; } };
    const req = { auth: as, params: {}, body: body || {}, query: {} };
    const run = i => { const f = chain[i]; if (i === chain.length - 1) return f(req, res, e => resolve({ status: e.http || 500, json: { error: e.message } })); f(req, res, e => (e ? resolve({ status: e.http || 500, json: { error: e.message } }) : run(i + 1))); };
    run(0);
  });
  const setSw = on => q("UPDATE app_settings SET features = COALESCE(features,'{}'::jsonb) || $1::jsonb WHERE id=1", [JSON.stringify({ offerPush: on })]);
  await q("UPDATE app_settings SET features='{}'::jsonb WHERE id=1"); await q('DELETE FROM offers');
  const mk = async (n, role, status = 'active') => (await q("INSERT INTO users(name, phone, password_hash, role, status) VALUES($1,$2,'x',$3,$4) RETURNING id", [n, '010' + String(Math.floor(Math.random() * 1e8)).padStart(8, '0'), role, status])).rows[0].id;
  const adm = await mk('م', 'admin'), c1 = await mk('ع1', 'customer'), c2 = await mk('ع2', 'customer'), cb = await mk('محظور', 'customer', 'suspended'), ow = await mk('ص', 'provider');
  const shop = (await q("INSERT INTO providers(owner_user_id,type,name,phone,status,is_open) VALUES($1,'restaurant','مطعم النور','01000000000','active',TRUE) RETURNING id", [ow])).rows[0].id;
  const A = { sub: String(adm), role: 'admin' };
  let r;
  console.log('A) switch OFF: offer is created, nobody is notified');
  r = await call('POST /api/admin/offers', A, { title: 'عرض 1', percent: 20 }); eq(r.status, 201, 'created'); eq(sent.length, 0, 'no push while OFF');
  console.log('B) switch ON: customers (active only) are notified');
  await setSw(true); await q('DELETE FROM offers');
  r = await call('POST /api/admin/offers', A, { title: 'عرض الجمعة', percent: 30, providerId: shop }); eq(r.status, 201, 'created');
  eq(sent.length, 1, 'one push'); const ids = sent[0].ids.map(Number);
  ok(ids.includes(Number(c1)) && ids.includes(Number(c2)), 'customers receive'); ok(!ids.includes(Number(cb)) && !ids.includes(Number(adm)) && !ids.includes(Number(ow)), 'blocked / owner / shop do not');
  ok(sent[0].p.title.includes('عرض الجمعة') && sent[0].p.body.includes('30') && sent[0].p.body.includes('مطعم النور'), 'text names the offer, percent and shop');
  console.log('C) daily cap');
  r = await call('POST /api/admin/offers', A, { title: 'عرض 2', percent: 10 }); eq(r.status, 201, 'second created'); eq(sent.length, 1, 'no second push within 24h');
  await q("UPDATE offers SET pushed_at = NOW() - INTERVAL '25 hours'");
  await call('POST /api/admin/offers', A, { title: 'عرض 3', percent: 15 }); eq(sent.length, 2, 'push again after 24h'); ok(sent[1].p.body.includes('كل المحلات'), 'global offer text');
  console.log('D) a push failure never fails the creation');
  await q("UPDATE offers SET pushed_at = NULL"); const o = require('../src/offers.js');
  const n = await o.notifyNewOffer(pool, async () => { throw new Error('fcm down'); }, (await q('SELECT id FROM offers LIMIT 1')).rows[0].id); eq(n, 0, 'swallowed');
  console.log('E) an offer that has not started / ended gets no push');
  await q("UPDATE offers SET pushed_at=NULL"); const id = (await q("INSERT INTO offers(title,percent,ends_at) VALUES('منتهي',10,NOW()-INTERVAL '1 hour') RETURNING id")).rows[0].id;
  eq(await o.notifyNewOffer(pool, pushToUsers, id), 0, 'ended offer: none');
  await q('DELETE FROM offers'); await setSw(false);
  console.log(bad ? `FAILED ${bad}` : 'ALL OK', 'pass=' + pass);
  await pool.end(); process.exit(bad ? 1 : 0);
})().catch(e => { console.error('CRASH', e); process.exit(2); });
