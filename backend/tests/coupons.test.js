const { Pool } = require('./shim');
let pass = 0, bad = 0; const ok = (c, m) => { if (c) pass++; else { bad++; console.log('  FAIL:', m); } };
const routes = {}; const app = {};
for (const m of ['get', 'post', 'patch', 'put', 'delete']) app[m] = (p, ...c) => { routes[`${m.toUpperCase()} ${p}`] = c; };
const asyncRoute = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
const positiveId = v => { const n = Number(v); return Number.isSafeInteger(n) && n > 0 ? n : null; };
const pass1 = (req, res, next) => next();
const pushes = [];
(async () => {
  const pool = new Pool(); const q = (t, p) => pool.query(t, p);
  await q('TRUNCATE coupon_uses, coupons CASCADE');
  const deps = { pool, auth: pass1, authAny: pass1, roles: () => pass1, asyncRoute, positiveId };
  require('../src/orders.js')(app, { ...deps, maintenanceState: async () => ({ enabled: true }), loadSettings: async () => ({}), cleanUser: x => x, pushToUsers: async (ids, p) => { pushes.push({ ids, p }); } });
  require('../src/coupons.js').registerCouponRoutes(app, deps);
  const call = (key, as, body, params) => new Promise(resolve => {
    const res = { set() { return this; }, status(c) { this.c = c; return this; }, json(j) { resolve({ status: this.c || 200, json: j }); return this; } };
    const chain = routes[key];
    chain[chain.length - 1]({ auth: as, params: params || {}, body: body || {}, query: {} }, res, e => resolve({ status: e.status || e.http || 500, json: { error: e.message } }));
  });
  const mk = async (n, role) => (await q("INSERT INTO users(name, phone, password_hash, role, status) VALUES($1,$2,'x',$3,'active') RETURNING id", [n, '010' + String(Math.floor(Math.random() * 1e8)).padStart(8, '0'), role])).rows[0].id;
  const adm = await mk('مالك', 'admin'), c1 = await mk('عميل1', 'customer'), c2 = await mk('عميل2', 'customer'), oA = await mk('صاحب أ', 'provider'), oB = await mk('صاحب ب', 'provider');
  const shop = async (o, n, fee) => (await q("INSERT INTO providers(owner_user_id,type,name,phone,status,is_open,delivery_fee) VALUES($1,'maker',$2,'01000000000','active',TRUE,$3) RETURNING id", [o, n, fee])).rows[0].id;
  const pA = await shop(oA, 'أ', 10), pB = await shop(oB, 'ب', 15);
  const prod = async (p, price) => (await q("INSERT INTO products(provider_id,name,price) VALUES($1,'منتج',$2) RETURNING id", [p, price])).rows[0].id;
  const xA = await prod(pA, 100), xB = await prod(pB, 60), xCheap = await prod(pA, 30);
  const ADM = { sub: String(adm), role: 'admin', status: 'active' };
  const C1 = { sub: String(c1), role: 'customer', status: 'active' }, C2 = { sub: String(c2), role: 'customer', status: 'active' };
  const base = { name: 'عميل', phone: '01012345678', address: 'شارع 5 عمارة 3 الدور 2', notes: '' };
  const buy = (as, lines, coupon) => call('POST /api/orders/checkout', as, { ...base, lines, coupon });
  const check = (as, lines, code) => call('POST /api/coupons/check', as, { lines, code });
  const mkCoupon = b => call('POST /api/admin/coupons', ADM, b);
  const last = async () => (await q('SELECT * FROM coupons ORDER BY id DESC LIMIT 1')).rows[0];
  const eq = (a, b, m) => ok(a === b, `${m}: got ${a}, want ${b}`);

  console.log('A) creating codes');
  eq((await mkCoupon({ code: 'save20', kind: 'amount', value: 20, days: 3 })).status, 201, 'amount code created');
  eq((await last()).code, 'SAVE20', 'code is stored in capitals');
  eq((await mkCoupon({ code: 'SAVE20', kind: 'amount', value: 5, days: 3 })).status, 409, 'duplicate code refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 3 })).status, 201, 'auto-generated code');
  ok(/^OFF-[A-Z2-9]{4}$/.test((await last()).code), 'auto code looks right: ' + (await last()).code);
  eq((await mkCoupon({ kind: 'percent', value: 95, days: 3 })).status, 400, 'percent above 90 refused');
  eq((await mkCoupon({ kind: 'amount', value: 0, days: 3 })).status, 400, 'zero value refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 0 })).status, 400, 'zero days refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 400 })).status, 400, 'too many days refused');
  eq((await mkCoupon({ code: 'a b', kind: 'amount', value: 5, days: 3 })).status, 400, 'short/odd code refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 3, providerIds: ['99999'] })).status, 404, 'unknown shop refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 3, userId: '99999' })).status, 404, 'unknown customer refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 3, startDate: '2020-01-01' })).status, 400, 'a period already over is refused');
  eq((await mkCoupon({ kind: 'amount', value: 5, days: 3, startDate: 'garbage' })).status, 400, 'bad start date refused');
  eq((await call('GET /api/admin/coupons', ADM)).json.coupons.length, 2, 'the list shows the two good codes');

  console.log('B) amount code on one shop');
  let r = await check(C1, [{ productId: xA, qty: 1 }], ' save20 ');
  eq(r.status, 200, 'check ok'); eq(r.json.discount, 20, 'check says 20');
  r = await buy(C1, [{ productId: xA, qty: 2 }], 'save20');
  eq(r.status, 201, 'checkout with code');
  let o = r.json.orders[0];
  eq(o.subtotal, 200, 'subtotal is the products'); eq(o.discount, 20, 'discount on the order'); eq(o.couponCode, 'SAVE20', 'code on the order'); eq(o.total, 200 - 20 + 10, 'total = products - discount + delivery');
  eq(r.json.invoice.total, 190, 'invoice total follows'); eq(r.json.invoice.parts[0].discount, 20, 'invoice part shows the discount');
  eq(Number((await q('SELECT total FROM orders WHERE id=$1', [o.id])).rows[0].total), 190, 'stored total');
  eq((await q('SELECT count(*)::int n FROM coupon_uses')).rows[0].n, 1, 'one use recorded');
  r = await buy(C1, [{ productId: xA, qty: 1 }], 'SAVE20');
  eq(r.status, 400, 'the same customer cannot use a one-use code twice'); ok(/استخدمت/.test(r.json.error), 'reason: ' + r.json.error);
  r = await check(C1, [{ productId: xA, qty: 1 }], 'SAVE20'); eq(r.status, 400, 'check also says used');
  eq((await q("SELECT count(*)::int n FROM orders WHERE customer_user_id=$1", [c1])).rows[0].n, 1, 'the refused checkout made no order');
  r = await buy(C2, [{ productId: xA, qty: 1 }], 'SAVE20'); eq(r.status, 201, 'another customer can use it');
  eq(r.json.orders[0].total, 100 - 20 + 10, 'his total');

  console.log('C) never below zero, never on delivery, percent cap');
  await mkCoupon({ code: 'BIG50', kind: 'amount', value: 50, days: 2, perUser: null });
  r = await buy(C1, [{ productId: xCheap, qty: 1 }], 'BIG50');
  eq(r.json.orders[0].discount, 30, 'discount is capped at the products price'); eq(r.json.orders[0].total, 10, 'only the delivery is left');
  await mkCoupon({ code: 'PCT10', kind: 'percent', value: 10, maxDiscount: 5, days: 2, perUser: null });
  r = await check(C1, [{ productId: xA, qty: 1 }], 'PCT10'); eq(r.json.discount, 5, '10% of 100 capped at 5');
  await mkCoupon({ code: 'PCT25', kind: 'percent', value: 25, days: 2, perUser: null });
  r = await check(C1, [{ productId: xA, qty: 1 }], 'PCT25'); eq(r.json.discount, 25, '25% of 100');
  r = await check(C1, [{ productId: xA, qty: 3 }, { productId: xCheap, qty: 1 }], 'PCT25'); eq(r.json.discount, 82.5, '25% of 330 = 82.5');

  console.log('D) dates and switch');
  await mkCoupon({ code: 'LATER', kind: 'amount', value: 5, days: 2, startDate: new Date(Date.now() + 5 * 864e5).toISOString().slice(0, 10), perUser: null });
  r = await check(C1, [{ productId: xA, qty: 1 }], 'LATER'); eq(r.status, 400, 'not started'); ok(/لم يبدأ/.test(r.json.error), r.json.error);
  await mkCoupon({ code: 'OLDONE', kind: 'amount', value: 5, days: 2, perUser: null });
  await q("UPDATE coupons SET starts_at=NOW()-interval '5 days', ends_at=NOW()-interval '1 day' WHERE code='OLDONE'");
  r = await check(C1, [{ productId: xA, qty: 1 }], 'OLDONE'); eq(r.status, 400, 'expired'); ok(/انتهت/.test(r.json.error), r.json.error);
  await mkCoupon({ code: 'PAUSED', kind: 'amount', value: 5, days: 2, perUser: null });
  const paused = await last();
  eq((await call('PATCH /api/admin/coupons/:id', ADM, { active: false }, { id: String(paused.id) })).status, 200, 'switch off');
  r = await check(C1, [{ productId: xA, qty: 1 }], 'PAUSED'); eq(r.status, 400, 'a stopped code is refused'); ok(/متوقف/.test(r.json.error), r.json.error);
  await call('PATCH /api/admin/coupons/:id', ADM, { active: true }, { id: String(paused.id) });
  eq((await check(C1, [{ productId: xA, qty: 1 }], 'PAUSED')).status, 200, 'switched on again');
  eq((await check(C1, [{ productId: xA, qty: 1 }], 'NOPE12')).status, 400, 'unknown code');
  eq((await check(C1, [{ productId: xA, qty: 1 }], '')).status, 400, 'empty code');

  console.log('E) chosen shops, several shops in one cart');
  await mkCoupon({ code: 'ONLYB', kind: 'amount', value: 10, days: 2, providerIds: [String(pB)], perUser: null });
  r = await check(C1, [{ productId: xA, qty: 1 }], 'ONLYB'); eq(r.status, 400, 'a cart of shop A cannot use a code of shop B'); ok(/لا ينطبق/.test(r.json.error), r.json.error);
  r = await buy(C1, [{ productId: xA, qty: 1 }, { productId: xB, qty: 1 }], 'ONLYB');
  eq(r.status, 201, 'mixed cart with a code of B');
  const oa = r.json.orders.find(x => x.providerId === String(pA)), ob = r.json.orders.find(x => x.providerId === String(pB));
  eq(oa.discount, undefined, 'shop A order has no discount'); eq(oa.total, 110, 'A total'); eq(ob.discount, 10, 'shop B order has the discount'); eq(ob.total, 60 - 10 + 15, 'B total');
  eq(r.json.invoice.total, 110 + 65, 'invoice is the sum');
  eq((await q('SELECT count(DISTINCT group_ref)::int n FROM coupon_uses WHERE coupon_id=(SELECT id FROM coupons WHERE code=$1)', ['ONLYB'])).rows[0].n, 1, 'a checkout counts as one use');
  await mkCoupon({ code: 'BOTH20', kind: 'amount', value: 20, days: 2, perUser: null });
  r = await buy(C1, [{ productId: xA, qty: 1 }, { productId: xB, qty: 1 }], 'BOTH20');
  const da = r.json.orders.find(x => x.providerId === String(pA)).discount, db_ = r.json.orders.find(x => x.providerId === String(pB)).discount;
  eq(Math.round((da + db_) * 100) / 100, 20, 'the split adds up to the full discount: ' + da + ' + ' + db_);
  ok(da > db_, 'the bigger shop carries more');
  eq(r.json.invoice.total, 160 + 25 - 20, 'invoice total after the split');
  eq((await q('SELECT count(*)::int n FROM coupon_uses WHERE coupon_id=(SELECT id FROM coupons WHERE code=$1)', ['BOTH20'])).rows[0].n, 2, 'a use per order');

  console.log('F) an offer and a code never stack');
  await q("INSERT INTO offers(title, percent, provider_id) VALUES('عرض', 10, $1)", [pA]);
  r = await check(C1, [{ productId: xA, qty: 1 }], 'BOTH20'); eq(r.status, 400, 'shop with an offer: the code is refused'); ok(/عرض/.test(r.json.error), r.json.error);
  r = await check(C1, [{ productId: xA, qty: 1 }, { productId: xB, qty: 1 }], 'BOTH20');
  eq(r.status, 200, 'mixed cart: the code works on the shop without an offer'); eq(r.json.discount, 20, 'discount only on shop B (60 -> 20 fits)');
  r = await buy(C1, [{ productId: xA, qty: 1 }, { productId: xB, qty: 1 }], 'BOTH20');
  eq(r.json.orders.find(x => x.providerId === String(pA)).discount, undefined, 'the offer shop gets no code discount');
  eq(r.json.orders.find(x => x.providerId === String(pA)).subtotal, 90, 'it keeps its offer price');
  await q('DELETE FROM offers');

  console.log('G) a private (gift) code');
  await mkCoupon({ code: 'ONLYC2', kind: 'amount', value: 15, days: 2, userId: String(c2) });
  r = await check(C1, [{ productId: xA, qty: 1 }], 'ONLYC2'); eq(r.status, 400, 'another customer cannot use it'); ok(/غير مخصص/.test(r.json.error), r.json.error);
  eq((await buy(C1, [{ productId: xA, qty: 1 }], 'ONLYC2')).status, 400, 'checkout refuses it too');
  eq((await check(C2, [{ productId: xA, qty: 1 }], 'ONLYC2')).status, 200, 'its owner can');
  let mine = await call('GET /api/coupons/mine', C2); ok(mine.json.coupons.some(x => x.code === 'ONLYC2'), 'it is saved in his list');
  eq((await call('GET /api/coupons/mine', C1)).json.coupons.some(x => x.code === 'ONLYC2'), false, 'not in the other customer\'s list');
  eq((await buy(C2, [{ productId: xA, qty: 1 }], 'ONLYC2')).status, 201, 'he uses it');
  mine = await call('GET /api/coupons/mine', C2); eq(mine.json.coupons.some(x => x.code === 'ONLYC2'), false, 'a used gift leaves his list');

  console.log('H) total uses and the race for the last one');
  await mkCoupon({ code: 'LAST1', kind: 'amount', value: 10, days: 2, maxUses: 1 });
  const [ra, rb] = await Promise.all([buy(C1, [{ productId: xA, qty: 1 }], 'LAST1'), buy(C2, [{ productId: xA, qty: 1 }], 'LAST1')]);
  eq([ra.status, rb.status].sort().join(','), '201,400', 'exactly one of two simultaneous checkouts gets the last use: ' + ra.status + ',' + rb.status);
  eq((await q("SELECT count(DISTINCT group_ref)::int n FROM coupon_uses WHERE coupon_id=(SELECT id FROM coupons WHERE code='LAST1')")).rows[0].n, 1, 'one use recorded');
  await mkCoupon({ code: 'TWICE', kind: 'amount', value: 5, days: 2, perUser: 2 });
  eq((await buy(C1, [{ productId: xA, qty: 1 }], 'TWICE')).status, 201, 'first use'); eq((await buy(C1, [{ productId: xA, qty: 1 }], 'TWICE')).status, 201, 'second use');
  eq((await buy(C1, [{ productId: xA, qty: 1 }], 'TWICE')).status, 400, 'third refused');

  console.log('I) a cancelled order gives the code back');
  await mkCoupon({ code: 'BACK10', kind: 'amount', value: 10, days: 2 });
  r = await buy(C1, [{ productId: xA, qty: 1 }], 'BACK10'); eq(r.status, 201, 'used');
  eq((await buy(C1, [{ productId: xA, qty: 1 }], 'BACK10')).status, 400, 'no second time');
  const cx = await call('POST /api/orders/:id/action', C1, { action: 'cancel' }, { id: r.json.orders[0].id });
  eq(cx.status, 200, 'customer cancels');
  eq((await q("SELECT count(*)::int n FROM coupon_uses WHERE coupon_id=(SELECT id FROM coupons WHERE code='BACK10')")).rows[0].n, 0, 'the use is given back');
  eq((await buy(C1, [{ productId: xA, qty: 1 }], 'BACK10')).status, 201, 'and he can use it again');

  console.log('J) the owner gifts a code when he cancels a refused order');
  const oG = (await buy(C1, [{ productId: xA, qty: 1 }])).json.orders[0];
  await call('POST /api/orders/:id/action', { sub: String(oA), role: 'provider', status: 'active' }, { action: 'reject', reason: 'x' }, { id: oG.id });
  pushes.length = 0;
  r = await call('POST /api/orders/:id/action', ADM, { action: 'cancel', reason: 'المحل رافض الطلب', gift: { kind: 'amount', value: 20, days: 7 } }, { id: oG.id });
  eq(r.status, 200, 'cancel with a gift'); ok(/^ABIS-[A-Z2-9]{4}$/.test(r.json.order.giftCode || ''), 'gift code on the order: ' + r.json.order.giftCode);
  const gc = (await q('SELECT * FROM coupons WHERE code=$1', [r.json.order.giftCode])).rows[0];
  ok(gc && Number(gc.user_id) === Number(c1) && Number(gc.per_user) === 1 && Number(gc.max_uses) === 1 && gc.source === 'gift' && Number(gc.value) === 20, 'a private one-use gift for this customer ' + JSON.stringify(gc));
  ok(new Date(gc.ends_at).getTime() > Date.now() + 6.9 * 864e5 && new Date(gc.ends_at).getTime() < Date.now() + 7.1 * 864e5, 'valid for 7 days');
  ok(pushes.some(x => x.ids.includes(c1) && /ABIS-/.test(x.p.body || '')), 'the customer is notified with the code: ' + JSON.stringify(pushes.map(x => x.p.body)));
  ok((await call('GET /api/coupons/mine', C1)).json.coupons.some(x => x.code === gc.code), 'saved in his list');
  eq((await check(C2, [{ productId: xA, qty: 1 }], gc.code)).status, 400, 'nobody else can use it');
  eq((await check(C1, [{ productId: xA, qty: 1 }], gc.code)).status, 200, 'he can');
  const oG2 = (await buy(C1, [{ productId: xA, qty: 1 }])).json.orders[0];
  await call('POST /api/orders/:id/action', { sub: String(oA), role: 'provider', status: 'active' }, { action: 'reject', reason: 'x' }, { id: oG2.id });
  r = await call('POST /api/orders/:id/action', ADM, { action: 'cancel', reason: 'سبب', gift: { kind: 'amount', value: 0, days: 7 } }, { id: oG2.id });
  eq(r.status, 400, 'a bad gift value is refused'); eq((await q('SELECT status FROM orders WHERE id=$1', [oG2.id])).rows[0].status, 'rejected', 'and the order is left untouched');
  r = await call('POST /api/orders/:id/action', { sub: String(c1), role: 'customer' }, { action: 'cancel', gift: { kind: 'amount', value: 500, days: 7 } }, { id: (await buy(C1, [{ productId: xA, qty: 1 }])).json.orders[0].id });
  eq(r.status, 200, 'a customer cancelling cannot give himself a gift'); eq(r.json.order.giftCode, undefined, 'no gift for him');
  const sync = await q('SELECT count(*)::int n FROM coupons WHERE source=$1', ['gift']); eq(sync.rows[0].n, 1, 'only one gift was ever made');

  console.log('K) deleting');
  await mkCoupon({ code: 'DEL12', kind: 'amount', value: 5, days: 2 }); const del = await last();
  eq((await call('DELETE /api/admin/coupons/:id', ADM, {}, { id: String(del.id) })).status, 200, 'an unused code can be deleted');
  const used = (await q("SELECT id FROM coupons WHERE code='SAVE20'")).rows[0];
  eq((await call('DELETE /api/admin/coupons/:id', ADM, {}, { id: String(used.id) })).status, 409, 'a used code cannot be deleted');
  const list = (await call('GET /api/admin/coupons', ADM)).json.coupons; const s20 = list.find(x => x.code === 'SAVE20');
  ok(s20 && s20.uses === 2 && s20.active, 'the list shows its uses: ' + (s20 && s20.uses));

  console.log('L) nothing changes without a code');
  r = await buy(C1, [{ productId: xA, qty: 1 }]); eq(r.status, 201, 'plain checkout'); eq(r.json.orders[0].total, 110, 'plain total'); eq(r.json.orders[0].discount, undefined, 'no discount field');
  eq((await buy(C1, [])).status, 400, 'empty cart still refused');
  console.log(`coupons: ${pass} passed, ${bad} failed`); await pool.end(); process.exit(bad ? 1 : 0);
})().catch(e => { console.error('CRASH', e); process.exit(2); });
