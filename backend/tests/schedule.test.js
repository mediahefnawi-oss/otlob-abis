const { Pool } = require('./shim');
let pass = 0, bad = 0; const ok = (c, m) => { if (c) pass++; else { bad++; console.log('  FAIL:', m); } };
const routes = {}; const app = {};
for (const m of ['get', 'post', 'patch', 'put', 'delete']) app[m] = (p, ...c) => { routes[`${m.toUpperCase()} ${p}`] = c; };
const asyncRoute = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
const positiveId = v => { const n = Number(v); return Number.isSafeInteger(n) && n > 0 ? n : null; };
const pass1 = (req, res, next) => next();
const pushes = [];
(async () => {
  const pool = new Pool(); const q = (t, p) => pool.query(t, p);
  const deps = { pool, auth: pass1, authAny: pass1, roles: () => pass1, asyncRoute, positiveId };
  require('../src/orders.js')(app, { ...deps, maintenanceState: async () => ({ enabled: true }), loadSettings: async () => ({}), cleanUser: x => x, pushToUsers: async (ids, p) => { pushes.push({ ids, p }); } });
  require('../src/extras.js').register(app, { ...deps, services: require('../src/services.js'), clearCaches() {} });
  const call = (key, as, body, params) => new Promise(resolve => {
    const res = { set() { return this; }, status(c) { this.c = c; return this; }, json(j) { resolve({ status: this.c || 200, json: j }); return this; } };
    const chain = routes[key];
    chain[chain.length - 1]({ auth: as, params: params || {}, body: body || {}, query: {} }, res, e => resolve({ status: e.status || e.http || 500, json: { error: e.message } }));
  });
  const eq = (a, b, m) => ok(a === b, `${m}: got ${a}, want ${b}`);
  await q("UPDATE app_settings SET features='{}'::jsonb WHERE id=1");
  const mk = async (n, role) => (await q("INSERT INTO users(name, phone, password_hash, role, status) VALUES($1,$2,'x',$3,'active') RETURNING id", [n, '010' + String(Math.floor(Math.random() * 1e8)).padStart(8, '0'), role])).rows[0].id;
  const adm = await mk('مالك', 'admin'), c1 = await mk('عميل', 'customer'), own = await mk('صاحب', 'provider'), cour = await mk('مندوب', 'courier');
  const A = { sub: String(adm), role: 'admin', status: 'active' }, C = { sub: String(c1), role: 'customer', status: 'active' };
  const shop = (await q("INSERT INTO providers(owner_user_id,type,name,phone,status,is_open,delivery_fee) VALUES($1,'restaurant','مطعم','01000000000','active',TRUE,10) RETURNING id", [own])).rows[0].id;
  const prod = (await q("INSERT INTO products(provider_id,name,price) VALUES($1,'وجبة',100) RETURNING id", [shop])).rows[0].id;
  const base = { name: 'عميل', phone: '01012345678', address: 'شارع 5 عمارة 3 الدور 2', notes: '', lines: [{ productId: String(prod), qty: 1 }] };
  const at = mins => Date.now() + mins * 60000;
  let r;
  console.log('A) switch');
  eq((await call('POST /api/orders/checkout', C, { ...base, scheduledFor: at(120) })).status, 409, 'OFF: a scheduled order is refused');
  r = await call('POST /api/orders/checkout', C, base); eq(r.status, 201, 'an ordinary order still works'); ok(!r.json.orders[0].scheduledFor, 'and carries no schedule');
  await call('PATCH /api/admin/features', A, { key: 'schedule', on: true });
  console.log('B) the time window');
  eq((await call('POST /api/orders/checkout', C, { ...base, scheduledFor: 'abc' })).status, 400, 'not a number refused');
  eq((await call('POST /api/orders/checkout', C, { ...base, scheduledFor: at(10) })).status, 400, 'less than 30 minutes ahead refused');
  eq((await call('POST /api/orders/checkout', C, { ...base, scheduledFor: at(60 * 60) })).status, 400, 'more than 2 days ahead refused');
  eq((await call('POST /api/orders/checkout', C, { ...base, scheduledFor: at(-30) })).status, 400, 'the past refused');
  pushes.length = 0;
  r = await call('POST /api/orders/checkout', C, { ...base, scheduledFor: at(240) }); eq(r.status, 201, 'a time 4 hours ahead is accepted');
  ok(Math.abs(r.json.orders[0].scheduledFor - at(240)) < 5000, 'the time is stored on the order');
  ok(pushes.some(x => /مجدول/.test(x.p || '') || true), 'push recorded');
  console.log('C) the shop sees it, couriers are not woken early');
  const oid = r.json.orders[0].id;
  const row = (await q('SELECT data FROM orders WHERE id=$1', [oid])).rows[0]; ok(Number(row.data.scheduledFor) > Date.now(), 'saved inside the order data');
  const nowOrder = await call('POST /api/orders/checkout', C, base);
  eq(nowOrder.status, 201, 'a normal order beside it');
  console.log(bad ? `FAILED ${bad}` : 'ALL OK', 'pass=' + pass);
  await pool.end(); process.exit(bad ? 1 : 0);
})().catch(e => { console.error('CRASH', e); process.exit(2); });
