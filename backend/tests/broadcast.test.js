const { Pool } = require('./shim');
const B = require('../src/broadcast.js');
let pass = 0, failN = 0;
const ok = (c, m) => { if (c) pass++; else { failN++; console.log('  FAIL:', m); } };
const eq = (a, b, m) => ok(JSON.stringify(a) === JSON.stringify(b), `${m}: got ${JSON.stringify(a)} expected ${JSON.stringify(b)}`);
const routes = {}; const app = {};
for (const m of ['get', 'post', 'patch', 'put', 'delete']) app[m] = (path, ...chain) => { routes[`${m.toUpperCase()} ${path}`] = chain; };
const asyncRoute = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
const positiveId = v => { const n = Number(v); return Number.isSafeInteger(n) && n > 0 ? n : null; };
const auth = (req, res, next) => { if (!req.auth) return res.status(401).json({ error: 'auth' }); next(); };
const roles = (...allowed) => (req, res, next) => { if (!req.auth || !allowed.includes(req.auth.role)) return res.status(403).json({ error: 'forbidden' }); next(); };
async function call(key, { as, body, params } = {}) {
  const chain = routes[key]; if (!chain) throw new Error('no route ' + key);
  const req = { auth: as, body: body || {}, query: {}, params: params || {} };
  const out = { status: 200, json: null };
  const res = { status(c) { out.status = c; return this; }, json(j) { out.json = j; return this; } };
  let i = 0, err = null;
  const next = e => { if (e) { err = e; return; } const f = chain[i++]; if (f) return f(req, res, next); };
  next();
  const t0 = Date.now();
  while (!err && out.json === null && Date.now() - t0 < 8000) await new Promise(r => setTimeout(r, 2));
  if (err) throw err;
  return out;
}
(async () => {
  const pool = new Pool(); const q = (t, p) => pool.query(t, p);
  await q('TRUNCATE broadcasts, broadcast_seen RESTART IDENTITY CASCADE');
  const pushes = [];
  B.register(app, { pool, auth, roles, asyncRoute, positiveId, pushToUsers: async (ids, p) => { pushes.push({ ids, p }); } });
  const mk = async (n, role) => Number((await q("INSERT INTO users(name, phone, password_hash, role, status) VALUES($1,$2,'x',$3,'active') RETURNING id", [n, '010' + String(Math.floor(Math.random() * 1e8)).padStart(8, '0'), role])).rows[0].id);
  const a = await mk('admin', 'admin'), c1 = await mk('c1', 'customer'), c2 = await mk('c2', 'customer'), d = await mk('d', 'courier'), p = await mk('p', 'provider');
  await q("INSERT INTO users(name, phone, password_hash, role, status) VALUES('blocked','01099999999','x','customer','blocked')").catch(() => {});
  const A = { sub: a, role: 'admin' }, C1 = { sub: c1, role: 'customer' }, D = { sub: d, role: 'courier' }, P = { sub: p, role: 'provider' };
  eq((await call('POST /api/admin/broadcasts', { as: C1, body: { title: 'x' } })).status, 403, 'customer cannot broadcast');
  eq((await call('POST /api/admin/broadcasts', { as: A, body: { title: '  ' } })).status, 400, 'title required');
  const r = await call('POST /api/admin/broadcasts', { as: A, body: { title: 'عرض', body: 'خصم', audience: 'all' } });
  eq(r.status, 201, 'sent'); await new Promise(x => setTimeout(x, 20));
  ok(pushes.length === 1 && pushes[0].ids.includes(c1) && pushes[0].ids.includes(d) && pushes[0].ids.includes(p) && !pushes[0].ids.includes(a), 'all = every active non-admin user, not the admin');
  eq(r.json.broadcast.sentTo, pushes[0].ids.length, 'sentTo counts recipients');
  await call('POST /api/admin/broadcasts', { as: A, body: { title: 'للمناديب', audience: 'courier' } }); await new Promise(x => setTimeout(x, 20));
  ok(pushes[1].ids.includes(d) && !pushes[1].ids.includes(c1) && !pushes[1].ids.includes(p), 'courier audience only couriers');
  const un = async U => (await call('GET /api/broadcasts/unread', { as: U })).json.broadcasts.map(x => x.title);
  eq((await un(C1)).sort(), ['عرض'], 'customer sees only the "all" message');
  eq((await un(D)).sort(), ['عرض', 'للمناديب'].sort(), 'courier sees both');
  const id = r.json.broadcast.id;
  await call('POST /api/broadcasts/:id/seen', { as: C1, params: { id } });
  eq(await un(C1), [], 'dismissed message does not come back');
  eq((await un(D)).length, 2, 'dismissal is per user');
  await q("INSERT INTO captain_profiles(user_id, type_id, model, color, plate, status) VALUES($1,NULL,'m','c','p','approved')", [p]).catch(async () => { await q("INSERT INTO captain_profiles(user_id) VALUES($1)", [p]).catch(() => {}); });
  await call('POST /api/admin/broadcasts', { as: A, body: { title: 'للكباتن', audience: 'captain' } });
  const had = (await q('SELECT 1 FROM captain_profiles WHERE user_id=$1', [p])).rowCount;
  if (had) eq((await un(P)).includes('للكباتن'), true, 'captain audience reaches captains'); 
  eq((await un(C1)).includes('للكباتن'), false, 'captain message not shown to a customer');
  const l = await call('GET /api/admin/broadcasts', { as: A });
  ok(l.json.broadcasts.length === 3 && l.json.counts.customer >= 2, 'admin list + counts');
  await call('DELETE /api/admin/broadcasts/:id', { as: A, params: { id } });
  eq((await call('GET /api/admin/broadcasts', { as: A })).json.broadcasts.length, 2, 'delete works');
  console.log(`broadcast: ${pass} passed, ${failN} failed`);
  await pool.end(); process.exit(failN ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
